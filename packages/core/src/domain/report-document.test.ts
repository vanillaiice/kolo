import assert from "node:assert/strict";
import { describe, it } from "node:test";

import { REPORT_KINDS, type ReportKind, type ReportResult } from "../application/report-views.ts";
import { formatMoney } from "./money.ts";
import { REPORT_DOCUMENT_LABELS, reportHtml, reportSheet, type ReportDocumentLabels, type ReportDocumentText } from "./report-document.ts";

const labels = Object.fromEntries(REPORT_DOCUMENT_LABELS.map(key => [key, `«${key}»`])) as ReportDocumentLabels;
const text: ReportDocumentText = { language: "fr", shop: "Boutique Awa", title: "Ventes", period: "1–19 oct. 2026", generated: "Imprimé le 19/10/2026", credit: "Generated by kolo · made by hblabs", labels };
const hostile = `<script>alert("x")</script> & 'Ndolé'`;

/** One result of every kind, with a hostile name wherever a business name appears and a negative figure where one can occur. */
const samples: Readonly<Record<ReportKind, ReportResult>> = {
  dashboard: { kind: "dashboard", salesMinor: 125_000, transactions: 12, grossProfitMinor: -3_000, costMinor: 128_000, linesWithoutCost: 2, expensesMinor: 5_000, netResultMinor: -8_000, customerDebtMinor: 10_000, supplierDebtMinor: 0, lowStock: 3 },
  sales: { kind: "sales", totalMinor: 125_000, transactions: 12, itemsSoldThousandths: 4_500 },
  salesByProduct: { kind: "salesByProduct", lines: [{ key: "p1", label: hostile, totalMinor: 9_000, count: 3 }, { key: "p2", label: "Riz", totalMinor: -500, count: 1 }], truncated: true },
  salesByCategory: { kind: "salesByCategory", lines: [{ key: "", label: "", totalMinor: 1_000, count: 1 }], truncated: false },
  salesByAccount: { kind: "salesByAccount", lines: [{ key: "a", label: "Espèces", totalMinor: 1_000, count: 1 }], truncated: false },
  salesByUser: { kind: "salesByUser", lines: [{ key: "u", label: "Awa", totalMinor: 1_000, count: 1 }], truncated: false },
  customerDebt: { kind: "customerDebt", lines: [], truncated: false },
  supplierDebt: { kind: "supplierDebt", lines: [{ key: "s", label: hostile, totalMinor: 2_000, count: 2 }], truncated: false },
  cashFlow: { kind: "cashFlow", accounts: [{ accountId: "a", name: hostile, inMinor: 5_000, outMinor: 7_000, netMinor: -2_000, closingMinor: 3_000 }] },
  valuation: { kind: "valuation", totalMinor: 40_000, uncosted: 1, truncated: false, products: [{ productId: "p", name: "Savon", onHandThousandths: -1_000 }, { productId: "q", name: "Huile", onHandThousandths: 2_000, unitCostMinor: 1_500, valueMinor: 3_000 }] },
  fastMoving: { kind: "fastMoving", products: [{ productId: "p", name: hostile, soldThousandths: 3_000, revenueMinor: 3_000, onHandThousandths: 0 }] },
  stockAlerts: { kind: "stockAlerts", products: [{ productId: "p", name: "Sel", onHandThousandths: -2_000 }], truncated: false },
  purchases: { kind: "purchases", totalMinor: 9_000, deliveries: 2, bySupplier: [{ key: "", label: "", totalMinor: 9_000, count: 2 }], truncated: false },
  tax: { kind: "tax", label: "TVA", grossMinor: 11_925, taxMinor: 1_925, netMinor: 10_000, groups: [{ rateBasisPoints: 1_925, grossMinor: 11_925, taxMinor: 1_925, netMinor: 10_000 }] },
};

describe("report document", () => {
  it("covers every report kind", () => {
    assert.deepEqual(Object.keys(samples).sort(), [...REPORT_KINDS].sort());
    for (const kind of REPORT_KINDS) {
      const sheet = reportSheet(samples[kind], labels, "fr");
      assert.ok(sheet.tiles.length > 0 || sheet.table !== undefined, kind);
      for (const row of sheet.table?.rows ?? []) assert.equal(row.length, sheet.table!.columns.length, `${kind} row width`);
    }
  });

  it("escapes every business name and holds no script or external resource", () => {
    for (const kind of REPORT_KINDS) {
      const html = reportHtml(samples[kind], { ...text, shop: hostile, title: hostile });
      assert.doesNotMatch(html, /<script/i, kind);
      assert.doesNotMatch(html, /(?:src|href)\s*=|url\(|@import/i, kind);
      assert.match(html, /default-src 'none'/);
    }
    const html = reportHtml(samples.salesByProduct, text);
    assert.ok(html.includes("&lt;script&gt;alert(&quot;x&quot;)&lt;/script&gt; &amp; &#39;Ndolé&#39;"));
  });

  it("writes exact money and marks negative figures", () => {
    const sheet = reportSheet(samples.cashFlow, labels, "fr");
    assert.deepEqual(sheet.table!.rows[0]!.map(cell => cell.text), [hostile, formatMoney(5_000), formatMoney(7_000), formatMoney(-2_000), formatMoney(3_000)]);
    assert.deepEqual(sheet.table!.rows[0]!.map(cell => cell.negative === true), [false, false, false, true, false]);
    const dashboard = reportSheet(samples.dashboard, labels, "en");
    assert.deepEqual(dashboard.tiles.find(([label]) => label === labels.netResult), [labels.netResult, formatMoney(-8_000, "en"), true]);
    assert.deepEqual(dashboard.notes, [`2 ${labels.uncostedLines}`]);
    assert.match(reportHtml(samples.cashFlow, text), /<td class="num neg">/);
  });

  it("names blank groups, unknown costs and negative stock", () => {
    assert.equal(reportSheet(samples.salesByCategory, labels, "fr").table!.rows[0]![0]!.text, labels.uncategorized);
    assert.equal(reportSheet(samples.purchases, labels, "fr").table!.rows[0]![0]!.text, labels.noSupplier);
    const valuation = reportSheet(samples.valuation, labels, "fr");
    assert.deepEqual(valuation.table!.rows[0]!.slice(2).map(cell => cell.text), ["—", "—"]);
    assert.deepEqual(valuation.notes, [`1 ${labels.uncostedProducts}`]);
    assert.equal(reportSheet(samples.stockAlerts, labels, "fr").table!.rows[0]![0]!.text, `Sel · ${labels.negativeStock}`);
  });

  it("says when a list is empty or cut at the row limit", () => {
    const empty = reportHtml(samples.customerDebt, text);
    assert.ok(empty.includes(`<p class="empty">${labels.noData}</p>`));
    assert.doesNotMatch(empty, /<table/);
    assert.ok(reportHtml(samples.salesByProduct, text).includes(labels.truncated));
    assert.ok(!reportHtml(samples.salesByUser, text).includes(labels.truncated));
  });

  it("frames the page with shop, title, period, print line and credit", () => {
    const html = reportHtml(samples.sales, text);
    for (const part of [text.shop, text.title, text.period, text.generated, text.credit]) assert.ok(html.includes(part), part);
    assert.match(html, /@page\{size:A4/);
    assert.match(html, /<html lang="fr">/);
  });
});
