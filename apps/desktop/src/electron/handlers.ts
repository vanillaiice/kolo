import type { DesktopStatus } from "./ipc.js";
import type { DesktopApplication } from "./application.ts";
import type { Result } from "../shared/service.js";

/** A host-owned dispatcher map; none of its channel names are supplied by the renderer API. */
export function desktopHandlers(current: DesktopApplication | (() => DesktopApplication), status: () => DesktopStatus, trusted: (event: unknown) => boolean): Readonly<Record<string, (event: unknown, ...args: unknown[]) => unknown>> {
  // Restore and pairing replace the application with one serving the activated database.
  const application = new Proxy({} as DesktopApplication, { get: (_target, key) => { const target = typeof current === "function" ? current() : current; const value: unknown = Reflect.get(target, key); return typeof value === "function" ? value.bind(target) : value; } });
  const handlers: Record<string, (event: unknown, ...args: unknown[]) => unknown> = {};
  const fail = (code: "permission_denied" | "invalid_input"): Result<never> => ({ ok: false, error: { code } });
  const query = (channel: string, operation: () => unknown): void => {
    handlers[channel] = (event, ...args) => !trusted(event) ? fail("permission_denied") : args.length !== 0 ? fail("invalid_input") : operation();
  };
  const command = (channel: string, operation: (input: unknown) => unknown): void => {
    handlers[channel] = (event, ...args) => !trusted(event) ? fail("permission_denied") : args.length !== 1 ? fail("invalid_input") : operation(args[0]);
  };
  handlers["kolo:installation-status"] = (event, ...args) => {
    if (!trusted(event) || args.length !== 0) throw new Error("invalid status caller");
    try { return status(); } catch { throw new Error("status unavailable"); }
  };
  query("kolo:workspace", () => application.getWorkspace());
  query("kolo:saved-shops", () => application.savedShops());
  command("kolo:open-saved-shop", input => application.openSavedShop(input));
  command("kolo:start-new-shop", input => application.startNewShop(input));
  query("kolo:lock", () => application.lock());
  command("kolo:setup", input => application.createShop(input));
  command("kolo:finish-setup", input => application.finishSetup(input));
  command("kolo:unlock", input => application.unlock(input));
  command("kolo:recover", input => application.recoverAccess(input));
  command("kolo:session-preferences", input => application.sessionPreferences(input));
  command("kolo:remember-session", input => application.setRememberSession(input));
  command("kolo:reset-computer", input => application.resetComputer(input));
  command("kolo:recovery-key", input => application.recoveryKey(input));
  command("kolo:products", input => application.listProducts(input));
  command("kolo:product", input => application.getProduct(input));
  command("kolo:scan", input => application.scanProduct(input));
  command("kolo:create-product", input => application.createProduct(input));
  command("kolo:update-product", input => application.updateProduct(input));
  command("kolo:product-active", input => application.setProductActive(input));
  command("kolo:product-photo", input => application.productPhoto(input));
  command("kolo:set-product-photo", input => application.setProductPhoto(input));
  command("kolo:remove-product-photo", input => application.removeProductPhoto(input));
  command("kolo:photo-usage", input => application.photoUsage(input));
  command("kolo:categories", input => application.listCategories(input));
  command("kolo:create-category", input => application.createCategory(input));
  command("kolo:update-category", input => application.updateCategory(input));
  command("kolo:move-stock", input => application.moveStock(input));
  command("kolo:count-stock", input => application.countStock(input));
  command("kolo:stock-history", input => application.stockHistory(input));
  command("kolo:payment-accounts", input => application.listPaymentAccounts(input));
  command("kolo:customers", input => application.listCustomers(input));
  command("kolo:customer", input => application.getCustomer(input));
  command("kolo:create-customer", input => application.createCustomer(input));
  command("kolo:update-customer", input => application.updateCustomer(input));
  command("kolo:customer-payment", input => application.receiveCustomerPayment(input));
  command("kolo:customer-statement", input => application.customerStatement(input));
  command("kolo:suppliers", input => application.listSuppliers(input));
  command("kolo:supplier", input => application.getSupplier(input));
  command("kolo:create-supplier", input => application.createSupplier(input));
  command("kolo:update-supplier", input => application.updateSupplier(input));
  command("kolo:supplier-payment", input => application.paySupplier(input));
  command("kolo:supplier-statement", input => application.supplierStatement(input));
  command("kolo:record-purchase", input => application.recordPurchase(input));
  command("kolo:purchases", input => application.listPurchases(input));
  command("kolo:purchase", input => application.getPurchase(input));
  command("kolo:accounts", input => application.listAccounts(input));
  command("kolo:create-account", input => application.createAccount(input));
  command("kolo:update-account", input => application.updateAccount(input));
  command("kolo:move-money", input => application.moveMoney(input));
  command("kolo:transfer-money", input => application.transferMoney(input));
  command("kolo:count-cash", input => application.countCash(input));
  command("kolo:correct-cash", input => application.correctCash(input));
  command("kolo:expenses", input => application.listExpenses(input));
  command("kolo:record-expense", input => application.recordExpense(input));
  command("kolo:reverse-expense", input => application.reverseExpense(input));
  command("kolo:report", input => application.report(input));
  command("kolo:analytics", input => application.analytics(input));
  command("kolo:journal", input => application.journal(input));
  command("kolo:journal-export", input => application.journalExport(input));
  command("kolo:held-back", input => application.heldBack(input));
  command("kolo:review-held-back", input => application.reviewHeldBack(input));
  command("kolo:save-csv", input => application.saveCsv(input));
  command("kolo:save-report-pdf", input => application.saveReportPdf(input));
  command("kolo:tax-settings", input => application.taxSettings(input));
  command("kolo:update-tax-settings", input => application.updateTaxSettings(input));
  command("kolo:product-tax", input => application.productTax(input));
  command("kolo:set-product-tax", input => application.setProductTax(input));
  command("kolo:payment-terms", input => application.paymentTerms(input));
  command("kolo:set-shop-terms", input => application.setShopTerms(input));
  command("kolo:credit-status", input => application.creditStatus(input));
  command("kolo:set-party-terms", input => application.setPartyTerms(input));
  command("kolo:notifications", input => application.notifications(input));
  command("kolo:mark-notifications", input => application.markNotifications(input));
  command("kolo:return-source", input => application.returnSource(input));
  command("kolo:preview-return", input => application.previewReturn(input));
  command("kolo:record-return", input => application.recordReturn(input));
  command("kolo:staff", input => application.listStaff(input));
  command("kolo:create-staff", input => application.createStaff(input));
  command("kolo:staff-permission", input => application.setStaffPermission(input));
  command("kolo:staff-role", input => application.setStaffRole(input));
  command("kolo:roles", input => application.listRoles(input));
  command("kolo:role-permission", input => application.setRolePermission(input));
  command("kolo:reset-role", input => application.resetRole(input));
  command("kolo:custom-roles", input => application.listCustomRoles(input));
  command("kolo:create-custom-role", input => application.createCustomRole(input));
  command("kolo:rename-custom-role", input => application.renameCustomRole(input));
  command("kolo:custom-role-permission", input => application.setCustomRolePermission(input));
  command("kolo:delete-custom-role", input => application.deleteCustomRole(input));
  command("kolo:staff-active", input => application.setStaffActive(input));
  command("kolo:reset-staff-secret", input => application.resetStaffSecret(input));
  query("kolo:discard-file", () => application.discardFile());
  command("kolo:save-backup", input => application.saveBackup(input));
  query("kolo:choose-import-file", () => application.chooseImportFile());
  command("kolo:open-backup", input => application.openBackup(input));
  command("kolo:backup-keys", input => application.backupKeys(input));
  command("kolo:prepare-backup-key", input => application.prepareBackupKey(input));
  command("kolo:confirm-backup-key", input => application.confirmBackupKey(input));
  command("kolo:restore-backup", input => application.restoreBackup(input));
  command("kolo:save-invite", input => application.saveInvite(input));
  command("kolo:open-pairing-request", input => application.openPairingRequest(input));
  command("kolo:approve-pairing-request", input => application.approvePairingRequest(input));
  query("kolo:open-invite", () => application.openInvite());
  command("kolo:accept-invite", input => application.acceptInvite(input));
  command("kolo:complete-pairing", input => application.completePairing(input));
  query("kolo:cancel-pairing", () => application.cancelPairing());
  command("kolo:exchange-state", input => application.exchangeState(input));
  command("kolo:save-exchange", input => application.saveExchange(input));
  command("kolo:open-exchange", input => application.openExchange(input));
  command("kolo:import-exchange", input => application.importExchange(input));
  command("kolo:save-import-receipt", input => application.saveImportReceipt(input));
  command("kolo:open-import-receipt", input => application.openImportReceipt(input));
  command("kolo:retry-exchange", input => application.retryExchange(input));
  command("kolo:server-state", input => application.serverState(input));
  command("kolo:check-server", input => application.checkServer(input));
  command("kolo:connect-server", input => application.connectServer(input));
  command("kolo:sync-server", input => application.syncServer(input));
  command("kolo:disconnect-server", input => application.disconnectServer(input));
  command("kolo:local-network-state", input => application.localNetworkState(input));
  command("kolo:stop-local-network", input => application.stopLocalNetwork(input));
  command("kolo:start-local-join", input => application.startLocalJoin(input));
  command("kolo:poll-local-join", input => application.pollLocalJoin(input));
  command("kolo:approve-local-join", input => application.approveLocalJoin(input));
  command("kolo:cancel-local-join", input => application.cancelLocalJoin(input));
  command("kolo:sync-local-network", input => application.syncLocalNetwork(input));
  command("kolo:lookup-local-join", input => application.lookupLocalJoin(input));
  command("kolo:request-local-join", input => application.requestLocalJoin(input));
  command("kolo:finish-local-join", input => application.finishLocalJoin(input));
  command("kolo:start-join-code", input => application.startJoinCode(input));
  command("kolo:poll-join-code", input => application.pollJoinCode(input));
  command("kolo:approve-join-code", input => application.approveJoinCode(input));
  command("kolo:cancel-join-code", input => application.cancelJoinCode(input));
  command("kolo:cash-accounts", input => application.listCashAccounts(input));
  command("kolo:checkout", input => application.checkout(input));
  command("kolo:receipt", input => application.getReceipt(input));
  command("kolo:receipts", input => application.listReceipts(input));
  return Object.freeze(handlers);
}
