import { nativeTransferCrypto } from "@kolo/core/backup/native-crypto";
import QuickCrypto, { Buffer } from "react-native-quick-crypto";
import { protectedCredentials, type CredentialCrypto } from "@kolo/core/identity/credentials";
import type { ExchangeCrypto } from "@kolo/core/exchange/types";
import type { CredentialPort } from "@kolo/core/identity/types";
import { secretStoreOnDevice } from "./store-on-device.ts";

/** Native asynchronous PBKDF2 and Ed25519; no JS digest or plaintext storage fallback. */
export const credentialCryptoOnDevice: CredentialCrypto = {
  randomHex: bytes => QuickCrypto.randomBytes(bytes).toString("hex"),
  derive: (secret, salt, iterations) => new Promise((resolve, reject) => {
    QuickCrypto.pbkdf2(secret, Buffer.from(salt, "hex"), iterations, 32, "sha256", (error, result) => {
      if (error != null || result === undefined) reject(new Error("native derivation unavailable"));
      else resolve(result.toString("hex"));
    });
  }),
  equalHex: (left, right) => /^[a-f0-9]{64}$/.test(left) && /^[a-f0-9]{64}$/.test(right) &&
    QuickCrypto.timingSafeEqual(Buffer.from(left, "hex"), Buffer.from(right, "hex")),
  sign: (privateKey, message) => new Promise((resolve, reject) => {
    QuickCrypto.sign(null, Buffer.from(message, "utf8"), privateKey, (error, signature) => {
      if (error != null || signature === undefined) reject(new Error("native signing unavailable")); else resolve(signature.toString("hex"));
    });
  }),
  deviceKey: () => new Promise((resolve, reject) => {
    QuickCrypto.generateKeyPair("ed25519", { publicKeyEncoding: { type: "spki", format: "pem" }, privateKeyEncoding: { type: "pkcs8", format: "pem" } },
      (error, publicKey, privateKey) => {
        if (error != null || typeof publicKey !== "string" || typeof privateKey !== "string") reject(new Error("native key generation unavailable"));
        else resolve({ publicKey, privateKey });
      });
  }),
};

/** Fresh installation/entity IDs generated by the native standard UUIDv7 implementation. */
export function newIdOnDevice(): string { return QuickCrypto.randomUUIDv7(); }

/** Credential vault backed by Expo's protected platform storage. Requires a rebuilt dev/production app. */
export function localCredentialsOnDevice(): CredentialPort {
  return protectedCredentials(secretStoreOnDevice(), credentialCryptoOnDevice);
}

/** Native SHA-256/Ed25519 bridge for signed journal events and destination receipts. */
export const exchangeCryptoOnDevice: ExchangeCrypto = {
  sha256: async message => { const hash = QuickCrypto.createHash("sha256"); hash.update(message, "utf8"); return hash.digest("hex"); },
  verify: (publicKey, message, signatureHex) => new Promise((resolve, reject) => {
    QuickCrypto.verify(null, Buffer.from(message, "utf8"), publicKey, Buffer.from(signatureHex, "hex"), (error, valid) => {
      if (error != null || valid === undefined) reject(new Error("native verification unavailable")); else resolve(valid);
    });
  }),
};

/** Native AES-256-GCM file encryption and bounded byte codecs; no plaintext or JS crypto fallback. */
export const transferCryptoOnDevice = nativeTransferCrypto({
 ...exchangeCryptoOnDevice,randomHex:credentialCryptoOnDevice.randomHex,derive:credentialCryptoOnDevice.derive,
 sha256Bytes:async bytes=>{const hash=QuickCrypto.createHash("sha256");hash.update(bytes);return hash.digest("hex");},
 encodeText:text=>new Uint8Array(Buffer.from(text,"utf8")),decodeText:bytes=>Buffer.from(bytes).toString("utf8"),
 encodeBase64:bytes=>Buffer.from(bytes).toString("base64"),decodeBase64:text=>new Uint8Array(Buffer.from(text,"base64")),
 fromHex:hex=>new Uint8Array(Buffer.from(hex,"hex")),toHex:bytes=>Buffer.from(bytes).toString("hex"),
 cipher:(key,nonce)=>QuickCrypto.createCipheriv("aes-256-gcm",Buffer.from(key,"hex"),Buffer.from(nonce,"hex"),{authTagLength:16}),
 decipher:(key,nonce)=>QuickCrypto.createDecipheriv("aes-256-gcm",Buffer.from(key,"hex"),Buffer.from(nonce,"hex"),{authTagLength:16}),
});
