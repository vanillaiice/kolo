import assert from "node:assert/strict";
import { test } from "node:test";
import type { Receipt } from "@kolo/core/application/queries";
import { receiptHtml, receiptText, type ReceiptLabels } from "./receipt-output.ts";

const labels: ReceiptLabels = { receipt: "Receipt", customer: "Customer", discount: "Discount", total: "Total", paid: "Paid", due: "Owing", returned: "Returned", date: "10 Oct 2026", footer: "Generated by kolo · made by hblabs" };
const saved: Receipt = { id: "s", number: "V-1", occurredAt: "2026-10-10T10:00:00.000Z", customerName: "<b>Awa</b> & co",
  lines: [{ id: "l", productId: "p", name: "Rice \"5kg\" <script>", quantity: 1500, unitPriceMinor: 1000, discountMinor: 0 }],
  payments: [{ id: "x", accountId: "a", name: "Cash", amountMinor: 1000 }], returnedMinor: 200, discountMinor: 100, totalMinor: 1400, paidMinor: 1000, outstandingMinor: 400 };

test("printable receipts escape every recorded value and keep the saved figures", () => {
  const html = receiptHtml(saved, "Shop <&>", labels);
  for (const raw of ["<script>", "<b>Awa</b>", "Shop <&>"]) assert.ok(!html.includes(raw), raw);
  assert.ok(html.includes("Rice &quot;5kg&quot; &lt;script&gt;")); assert.ok(html.includes("&lt;b&gt;Awa&lt;/b&gt; &amp; co"));
  for (const label of ["Discount", "Owing", "Returned", "Generated by kolo · made by hblabs", "72mm"]) assert.ok(html.includes(label), label);
});

test("shared text receipts list lines, settlement and returns from saved facts only", () => {
  const text = receiptText(saved, "Shop", labels);
  assert.match(text, /Receipt V-1/); assert.match(text, /Customer: <b>Awa<\/b> & co/);
  assert.ok(text.includes("Owing")); assert.ok(text.includes("Returned")); assert.ok(text.includes("Cash"));
  const settled = receiptText({ ...saved, customerName: undefined, outstandingMinor: 0, returnedMinor: 0, discountMinor: 0 }, "Shop", labels);
  for (const absent of ["Customer", "Owing", "Returned", "Discount"]) assert.ok(!settled.includes(absent), absent);
});

test("receipts show the tax included per rate and the shop's tax number, escaped, only when the sale carried tax", () => {
  const taxed: Receipt = { ...saved, tax: { label: "TVA <x>", registration: "M01 & 2", groups: [{ rateBasisPoints: 1925, grossMinor: 1400, taxMinor: 226, netMinor: 1174 }] } };
  const text = receiptText(taxed, "Shop", { ...labels, taxIncluded: "incl.", taxNumber: "Tax no." });
  assert.ok(text.includes("incl. TVA <x> 19,25 %: 226"), text); assert.ok(text.includes("Tax no. M01 & 2"));
  const html = receiptHtml(taxed, "Shop", { ...labels, taxIncluded: "incl.", taxNumber: "Tax no." });
  assert.ok(html.includes("TVA &lt;x&gt;")); assert.ok(html.includes("M01 &amp; 2")); assert.ok(!html.includes("<x>"));
  assert.ok(!receiptText(saved, "Shop", labels).includes("TVA"));
});
