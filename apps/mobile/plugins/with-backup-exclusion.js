/**
 * Keeps every shop file out of Android's own backups (ADR-035, milestone 1 item 9).
 *
 * KOLO owns backup and recovery: its encrypted containers are the only copies meant to leave the phone. Android's Auto
 * Backup would otherwise copy the business database and plaintext staging snapshots to the user's cloud account, and
 * Android 12+ device-to-device transfer ignores `allowBackup` unless data-extraction rules say otherwise. So the
 * manifest disables backup and points at rules that exclude every domain from both cloud backup and device transfer.
 * The android directory is regenerated by `expo prebuild`, hence a config plugin rather than an edit.
 */
const { withAndroidManifest, withDangerousMod } = require("expo/config-plugins");
const { mkdirSync, writeFileSync } = require("node:fs");
const { join } = require("node:path");

const RULES = "kolo_data_extraction_rules";
const DOMAINS = ["root", "file", "database", "sharedpref", "external"];
const excluded = DOMAINS.map(domain => `    <exclude domain="${domain}" path="." />`).join("\n");
const XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-backup-exclusion.js: nothing of KOLO's leaves the phone through Android backups. -->
<data-extraction-rules>
  <cloud-backup>
${excluded}
  </cloud-backup>
  <device-transfer>
${excluded}
  </device-transfer>
</data-extraction-rules>
`;

module.exports = function withBackupExclusion(config) {
  config = withAndroidManifest(config, result => {
    const application = result.modResults.manifest.application?.[0];
    if (application !== undefined) {
      application.$["android:allowBackup"] = "false";
      application.$["android:dataExtractionRules"] = `@xml/${RULES}`;
      delete application.$["android:fullBackupContent"];
    }
    return result;
  });
  return withDangerousMod(config, ["android", async result => {
    const directory = join(result.modRequest.platformProjectRoot, "app", "src", "main", "res", "xml");
    mkdirSync(directory, { recursive: true });
    writeFileSync(join(directory, `${RULES}.xml`), XML);
    return result;
  }]);
};

module.exports.XML = XML;
