/** Generate the public API reference from TypeScript declarations and JSDoc. */
import ts from "typescript";
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative } from "node:path";

const roots = ["packages/core/src", "packages/contracts/src", "apps/server/src", "apps/desktop/src/electron", "apps/desktop/src/shared"];
function walk(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => entry.isDirectory()
    ? walk(join(directory, entry.name)) : entry.name.endsWith(".ts") && !entry.name.endsWith(".test.ts") ? [join(directory, entry.name)] : []);
}
const files = roots.flatMap(walk).map(path => path.replaceAll("\\", "/")).sort();
const program = ts.createProgram(files, { target: ts.ScriptTarget.ES2023, module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext, skipLibCheck: true });
const checker = program.getTypeChecker();
const printer = ts.createPrinter({ removeComments: true });
const exported = node => ts.getModifiers(node)?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)
  && !node.jsDoc?.some(doc => doc.tags?.some(tag => tag.tagName.text === "internal"));
function documentation(node) {
  return (node.jsDoc ?? []).map(doc => typeof doc.comment === "string" ? doc.comment : (doc.comment ?? []).map(part => part.text ?? "").join("")).join("\n\n");
}
function functionSignature(node, file) {
  const signature = checker.getSignatureFromDeclaration(node);
  const returned = signature ? checker.typeToString(checker.getReturnTypeOfSignature(signature)) : "unknown";
  const params = node.parameters.map(parameter => printer.printNode(ts.EmitHint.Unspecified, parameter, file)).join(", ");
  const generic = node.typeParameters?.length ? `<${node.typeParameters.map(p => p.getText(file)).join(", ")}>` : "";
  return `${node.name?.getText(file) ?? "constructor"}${generic}(${params})${ts.isConstructorDeclaration(node) ? "" : `: ${returned}`};`;
}
const chunks = ["# Public TypeScript API reference\n\nGenerated by `npm run docs:api`. Do not edit this file directly. Source JSDoc owns function behavior; the architecture guide documents transactions, authorization, errors, and planned APIs. Only declarations in current code appear here.\n"];
for (const path of files) {
  const source = program.getSourceFile(path);
  const declarations = source.statements.filter(exported);
  if (declarations.length === 0) continue;
  const link = relative("docs/reference", path).replaceAll("\\", "/");
  chunks.push(`\n## [${path}](${link})\n`);
  for (const node of declarations) {
    const prose = documentation(node);
    if (prose) chunks.push(`\n${prose}\n`);
    let text;
    if (ts.isFunctionDeclaration(node)) text = functionSignature(node, source);
    else if (ts.isClassDeclaration(node)) {
      const members = node.members.filter(member => !ts.isPrivateIdentifier(member.name ?? ts.factory.createIdentifier("_"))
        && !ts.getModifiers(member)?.some(modifier => [ts.SyntaxKind.PrivateKeyword, ts.SyntaxKind.ProtectedKeyword].includes(modifier.kind)));
      text = `class ${node.name.text}${node.heritageClauses?.map(h => ` ${h.getText(source)}`).join("") ?? ""} {\n`;
      text += members.map(member => {
        const note = documentation(member);
        const comment = note ? `  /** ${note.replaceAll("\n", "\n   * ")} */\n` : "";
        if (ts.isConstructorDeclaration(member) || ts.isMethodDeclaration(member)) return `${comment}  ${functionSignature(member, source)}`;
        if (ts.isPropertyDeclaration(member)) return `${comment}  ${member.name.getText(source)}: ${member.type?.getText(source) ?? checker.typeToString(checker.getTypeAtLocation(member))};`;
        return "";
      }).filter(Boolean).join("\n") + "\n}";
    } else if (ts.isVariableStatement(node)) {
      text = node.declarationList.declarations.map(declaration => {
        const type = declaration.type?.getText(source) ?? checker.typeToString(checker.getTypeAtLocation(declaration), undefined, ts.TypeFormatFlags.NoTruncation);
        return `const ${declaration.name.getText(source)}: ${type};`;
      }).join("\n");
    } else text = printer.printNode(ts.EmitHint.Unspecified, node, source);
    chunks.push(`\n\`\`\`ts\n${text}\n\`\`\`\n`);
  }
}
const output = chunks.join("");
const destination = "docs/reference/typescript-api.md";
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== output) { process.stderr.write("API reference is stale; run npm run docs:api\n"); process.exit(1); }
} else { mkdirSync("docs/reference", { recursive: true }); writeFileSync(destination, output); }
